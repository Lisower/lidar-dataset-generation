//! Блокировка горячих клавиш сцены при открытом модальном окне.
//!
//! Модальные окна (например, выбор пресетов по `Ctrl + S`) при открытии
//! выставляют [`UiModalOpen(true)`](UiModalOpen). Пока окно открыто, горячие
//! клавиши общей сцены (`R`, `V`, `Tab`, движение камеры и т.п.) не должны
//! срабатывать — работают только «оконные» клавиши (закрытие, выбор, Enter).
//!
//! Системы горячих клавиш обычно начинаются с
//! `if ui.0 { return; }`, а системы модального окна, наоборот, проверяют
//! `if !ui.0 { return; }`.

use bevy::prelude::Resource;

/// Признак того, что поверх сцены открыто модальное окно.
///
/// `false` — сцена активна (обычное состояние), `true` — горячие клавиши
/// сцены приглушены. Выставляет bevy-utils (окно UI), читают системы
/// горячих клавиш нижнего уровня.
#[derive(Resource, Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct UiModalOpen(pub bool);

impl UiModalOpen {
    /// Модальное окно открыто.
    pub const OPEN: Self = Self(true);
    /// Модальное окно закрыто (обычное состояние).
    pub const CLOSED: Self = Self(false);
}
