/// Цвет рамы/коробки окон и дверей.
pub const FRAME: Color = Color::srgb(0.24, 0.22, 0.20);

/// Цвет ограждения балкона (тёмный металл/кованый).
pub const BALCONY_RAILING: Color = Color::srgb(0.30, 0.30, 0.32);

/// Цвет «скамейки»/перекрытия балкона.
pub const BALCONY_SLAB: Color = Color::srgb(0.55, 0.53, 0.48);

/// Цвет дымохода (красный печной кирпич).
pub const CHIMNEY: Color = Color::srgb(0.55, 0.26, 0.20);

/// Случайный цвет из палитры.
pub fn pick<R: Rng + ?Sized>(rng: &mut R, palette: &[Color]) -> Color {
    let idx = rng.random_range(0..palette.len());
    palette[idx]
}
